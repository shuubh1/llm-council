"""Standalone Document & File Generation Engine (PDF, DOCX, XLSX, CSV, MD, TXT)."""

import os
import re
import csv
import io
import json
import uuid
from pathlib import Path
from datetime import datetime
from typing import Dict, Any, List, Optional, Tuple
from .config import EXPORTS_DIR


INDEX_PATH = os.path.join(EXPORTS_DIR, "index.json")


def ensure_exports_dir(conversation_id: str = "general") -> str:
    conv_dir = os.path.join(EXPORTS_DIR, conversation_id)
    Path(conv_dir).mkdir(parents=True, exist_ok=True)
    return conv_dir


def _load_index() -> Dict[str, Any]:
    Path(EXPORTS_DIR).mkdir(parents=True, exist_ok=True)
    if not os.path.exists(INDEX_PATH):
        return {}
    try:
        with open(INDEX_PATH, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return {}


def _save_index(index_data: Dict[str, Any]):
    Path(EXPORTS_DIR).mkdir(parents=True, exist_ok=True)
    with open(INDEX_PATH, "w", encoding="utf-8") as f:
        json.dump(index_data, f, indent=2)


def sanitize_filename(title: str) -> str:
    clean = re.sub(r"[^a-zA-Z0-9_\-\. ]+", "", title or "Council_Document").strip()
    clean = re.sub(r"\s+", "_", clean)
    return clean[:80] or "Council_Document"


def _latin1_safe(text: str) -> str:
    """Convert common Unicode punctuation/symbols into core-font-safe equivalents for FPDF."""
    replacements = {
        "\u2018": "'",
        "\u2019": "'",
        "\u201c": '"',
        "\u201d": '"',
        "\u2013": "-",
        "\u2014": "--",
        "\u2022": "*",
        "\u2026": "...",
        "\u2192": "->",
        "\u2190": "<-",
        "\u21d2": "=>",
        "\u2713": "[x]",
        "\u2714": "[x]",
        "\u2717": "[ ]",
        "\u00a0": " ",
        "\u2265": ">=",
        "\u2264": "<=",
        "\u2260": "!=",
    }
    for k, v in replacements.items():
        text = text.replace(k, v)
    return text.encode("latin-1", errors="replace").decode("latin-1")


def _strip_inline_md(text: str) -> str:
    """Remove raw markdown bold/italic/code markers for clean text rendering."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"__(.+?)__", r"\1", text)
    text = re.sub(r"`([^`]+)`", r"\1", text)
    return text


def generate_pdf_file(filepath: str, title: str, content: str):
    """Generate a styled multi-page PDF document using fpdf2."""
    from fpdf import FPDF

    class CouncilPDF(FPDF):
        def header(self):
            self.set_font("Helvetica", "B", 9)
            self.set_text_color(100, 116, 139)
            self.cell(0, 8, _latin1_safe(f"LLM Council Synthesis Report | {title[:60]}"), border=False, align="R")
            self.ln(10)
            self.set_draw_color(226, 232, 240)
            self.line(15, 18, self.w - 15, 18)

        def footer(self):
            self.set_y(-15)
            self.set_font("Helvetica", "I", 8)
            self.set_text_color(148, 163, 184)
            self.cell(0, 10, f"Page {self.page_no()}/{{nb}} - Generated by LLM Council Console", align="C")

    pdf = CouncilPDF()
    pdf.alias_nb_pages()
    pdf.set_auto_page_break(auto=True, margin=18)
    pdf.set_margins(15, 22, 15)
    pdf.add_page()

    # Document Title Banner
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(15, 23, 42)
    pdf.multi_cell(0, 10, _latin1_safe(_strip_inline_md(title)))
    pdf.ln(2)
    pdf.set_font("Helvetica", "", 9)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(0, 6, f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}", ln=True)
    pdf.ln(4)

    lines = content.splitlines()
    in_code_block = False
    table_buffer: List[List[str]] = []

    def flush_table():
        nonlocal table_buffer
        if not table_buffer:
            return
        num_cols = max(len(r) for r in table_buffer)
        if num_cols == 0:
            table_buffer = []
            return
        usable_w = pdf.w - 30
        col_w = usable_w / num_cols
        pdf.ln(2)
        for r_idx, row in enumerate(table_buffer):
            if r_idx == 0:
                pdf.set_font("Helvetica", "B", 9)
                pdf.set_fill_color(241, 245, 249)
            else:
                pdf.set_font("Helvetica", "", 9)
                pdf.set_fill_color(255, 255, 255)
            pdf.set_text_color(30, 41, 59)
            for c_idx in range(num_cols):
                cell_val = row[c_idx] if c_idx < len(row) else ""
                cell_text = _latin1_safe(_strip_inline_md(cell_val))[:55]
                pdf.cell(col_w, 7, cell_text, border=1, fill=(r_idx == 0))
            pdf.ln(7)
        pdf.ln(3)
        table_buffer = []

    for raw_line in lines:
        line = raw_line.rstrip()

        if line.strip().startswith("```"):
            flush_table()
            in_code_block = not in_code_block
            pdf.ln(2)
            continue

        if in_code_block:
            pdf.set_font("Courier", "", 9)
            pdf.set_text_color(30, 41, 59)
            pdf.set_fill_color(248, 250, 252)
            pdf.multi_cell(0, 5, _latin1_safe(line or " "), fill=True)
            continue

        # Check for markdown table row
        if line.strip().startswith("|") and line.strip().endswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            # Skip separator rows like |---|---|
            if all(re.match(r"^[:\-]+$", c) for c in cells if c):
                continue
            table_buffer.append(cells)
            continue
        else:
            flush_table()

        if not line.strip():
            pdf.ln(3)
            continue

        if line.startswith("# "):
            pdf.ln(3)
            pdf.set_font("Helvetica", "B", 15)
            pdf.set_text_color(15, 23, 42)
            pdf.multi_cell(0, 8, _latin1_safe(_strip_inline_md(line[2:].strip())))
            pdf.ln(1)
        elif line.startswith("## "):
            pdf.ln(2)
            pdf.set_font("Helvetica", "B", 13)
            pdf.set_text_color(30, 58, 138)
            pdf.multi_cell(0, 7, _latin1_safe(_strip_inline_md(line[3:].strip())))
            pdf.ln(1)
        elif line.startswith("### "):
            pdf.ln(1)
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(30, 41, 59)
            pdf.multi_cell(0, 6, _latin1_safe(_strip_inline_md(line[4:].strip())))
        elif re.match(r"^\s*[\-\*]\s+", line):
            bullet_text = re.sub(r"^\s*[\-\*]\s+", "", line)
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(51, 65, 85)
            pdf.multi_cell(0, 6, _latin1_safe(f"  * {_strip_inline_md(bullet_text)}"))
        else:
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(51, 65, 85)
            pdf.multi_cell(0, 6, _latin1_safe(_strip_inline_md(line)))

    flush_table()
    pdf.output(filepath)


def generate_docx_file(filepath: str, title: str, content: str):
    """Generate a formatted Word (.docx) document using python-docx."""
    from docx import Document
    from docx.shared import Pt, RGBColor

    doc = Document()
    title_heading = doc.add_heading(_strip_inline_md(title), level=0)
    for run in title_heading.runs:
        run.font.color.rgb = RGBColor(15, 23, 42)

    meta_p = doc.add_paragraph(f"Generated by LLM Council Console • {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}")
    if meta_p.runs:
        meta_p.runs[0].font.size = Pt(9)
        meta_p.runs[0].font.color.rgb = RGBColor(100, 116, 139)

    lines = content.splitlines()
    in_code_block = False
    code_lines: List[str] = []
    table_buffer: List[List[str]] = []

    def flush_docx_table():
        nonlocal table_buffer
        if not table_buffer:
            return
        num_cols = max(len(r) for r in table_buffer)
        if num_cols > 0:
            tbl = doc.add_table(rows=len(table_buffer), cols=num_cols)
            tbl.style = "Table Grid"
            for r_i, row in enumerate(table_buffer):
                for c_i in range(num_cols):
                    val = row[c_i] if c_i < len(row) else ""
                    cell = tbl.cell(r_i, c_i)
                    cell.text = _strip_inline_md(val)
                    if r_i == 0 and cell.paragraphs and cell.paragraphs[0].runs:
                        cell.paragraphs[0].runs[0].bold = True
        table_buffer = []

    def add_formatted_paragraph(p_obj, raw_text: str):
        # Parse **bold** segments
        parts = re.split(r"(\*\*.*?\*\*)", raw_text)
        for part in parts:
            if part.startswith("**") and part.endswith("**"):
                run = p_obj.add_run(part[2:-2])
                run.bold = True
            else:
                p_obj.add_run(part)

    for raw_line in lines:
        line = raw_line.rstrip()
        if line.strip().startswith("```"):
            flush_docx_table()
            if in_code_block:
                p = doc.add_paragraph()
                run = p.add_run("\n".join(code_lines))
                run.font.name = "Courier New"
                run.font.size = Pt(9.5)
                code_lines = []
                in_code_block = False
            else:
                in_code_block = True
            continue

        if in_code_block:
            code_lines.append(line)
            continue

        if line.strip().startswith("|") and line.strip().endswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if all(re.match(r"^[:\-]+$", c) for c in cells if c):
                continue
            table_buffer.append(cells)
            continue
        else:
            flush_docx_table()

        if not line.strip():
            continue

        if line.startswith("# "):
            doc.add_heading(_strip_inline_md(line[2:].strip()), level=1)
        elif line.startswith("## "):
            doc.add_heading(_strip_inline_md(line[3:].strip()), level=2)
        elif line.startswith("### "):
            doc.add_heading(_strip_inline_md(line[4:].strip()), level=3)
        elif re.match(r"^\s*[\-\*]\s+", line):
            bullet_text = re.sub(r"^\s*[\-\*]\s+", "", line)
            p = doc.add_paragraph(style="List Bullet")
            add_formatted_paragraph(p, bullet_text)
        elif re.match(r"^\s*\d+\.\s+", line):
            num_text = re.sub(r"^\s*\d+\.\s+", "", line)
            p = doc.add_paragraph(style="List Number")
            add_formatted_paragraph(p, num_text)
        else:
            p = doc.add_paragraph()
            add_formatted_paragraph(p, line)

    flush_docx_table()
    doc.save(filepath)


def _extract_tabular_rows(content: str) -> List[List[str]]:
    """Extract rows from either Markdown tables or CSV lines in content."""
    lines = [l.strip() for l in content.strip().splitlines() if l.strip()]
    md_rows = []
    for line in lines:
        if line.startswith("|") and line.endswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(re.match(r"^[:\-]+$", c) for c in cells if c):
                continue
            md_rows.append([_strip_inline_md(c) for c in cells])
    if md_rows:
        return md_rows

    # Try CSV parsing if comma-separated lines exist
    csv_lines = [l for l in lines if not l.startswith("```")]
    try:
        reader = list(csv.reader(io.StringIO("\n".join(csv_lines))))
        if len(reader) > 1 and max(len(r) for r in reader) > 1:
            return reader
    except Exception:
        pass

    # Fallback: turn lines into Key / Content rows
    rows = [["Section / Line", "Content"]]
    for idx, line in enumerate(lines, start=1):
        rows.append([str(idx), _strip_inline_md(line)])
    return rows


def generate_xlsx_file(filepath: str, title: str, content: str):
    """Generate a styled Excel (.xlsx) spreadsheet using openpyxl."""
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment

    wb = Workbook()
    ws = wb.active
    ws.title = sanitize_filename(title)[:31] or "Sheet1"

    rows = _extract_tabular_rows(content)
    header_fill = PatternFill(start_color="1E3A8A", end_color="1E3A8A", fill_type="solid")
    header_font = Font(bold=True, color="FFFFFF")

    for r_idx, row in enumerate(rows, start=1):
        ws.append(row)
        if r_idx == 1:
            for c_idx in range(1, len(row) + 1):
                cell = ws.cell(row=1, column=c_idx)
                cell.fill = header_fill
                cell.font = header_font
                cell.alignment = Alignment(wrap_text=True, vertical="center")
        else:
            for c_idx in range(1, len(row) + 1):
                cell = ws.cell(row=r_idx, column=c_idx)
                cell.alignment = Alignment(wrap_text=True, vertical="top")

    # Auto-fit column widths
    for col in ws.columns:
        max_len = max((len(str(cell.value or "")) for cell in col), default=12)
        col_letter = col[0].column_letter
        ws.column_dimensions[col_letter].width = min(max(max_len + 4, 14), 60)

    wb.save(filepath)


def generate_csv_file(filepath: str, content: str):
    """Generate a clean RFC-4180 CSV file."""
    rows = _extract_tabular_rows(content)
    with open(filepath, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerows(rows)


def create_export_file(
    conversation_id: str,
    title: str,
    content: str,
    file_format: str = "pdf",
) -> Dict[str, Any]:
    """
    Generate a physical downloadable file in data/exports/{conversation_id}/
    and register it in the exports index.
    """
    fmt = (file_format or "pdf").lower().lstrip(".")
    if fmt not in ("pdf", "docx", "xlsx", "csv", "md", "txt"):
        fmt = "md"

    conv_dir = ensure_exports_dir(conversation_id or "general")
    file_id = f"file-{uuid.uuid4().hex[:12]}"
    safe_base = sanitize_filename(title)
    filename = f"{safe_base}.{fmt}"
    physical_path = os.path.join(conv_dir, f"{file_id}_{filename}")

    if fmt == "pdf":
        generate_pdf_file(physical_path, title, content)
    elif fmt == "docx":
        generate_docx_file(physical_path, title, content)
    elif fmt == "xlsx":
        generate_xlsx_file(physical_path, title, content)
    elif fmt == "csv":
        generate_csv_file(physical_path, content)
    elif fmt == "txt":
        plain = _strip_inline_md(content)
        with open(physical_path, "w", encoding="utf-8") as f:
            f.write(f"{title}\n{'=' * len(title)}\n\n{plain}\n")
    else:  # md
        with open(physical_path, "w", encoding="utf-8") as f:
            f.write(f"# {title}\n\n{content}\n")

    size_bytes = os.path.getsize(physical_path) if os.path.exists(physical_path) else 0

    record = {
        "id": file_id,
        "conversation_id": conversation_id or "general",
        "title": title,
        "filename": filename,
        "format": fmt,
        "size_bytes": size_bytes,
        "physical_path": physical_path,
        "preview_content": content[:8000],
        "download_url": f"/api/files/download/{file_id}",
        "created_at": datetime.utcnow().isoformat(),
    }

    idx = _load_index()
    idx[file_id] = record
    _save_index(idx)

    return record


def get_export_file(file_id: str) -> Optional[Dict[str, Any]]:
    """Lookup a generated file record by file_id."""
    idx = _load_index()
    rec = idx.get(file_id)
    if rec and os.path.exists(rec.get("physical_path", "")):
        return rec
    return None


def extract_and_compile_artifacts(
    conversation_id: str,
    response_text: str,
) -> Tuple[str, List[Dict[str, Any]]]:
    """
    Scan Chairman response for <artifact type="pdf|docx|xlsx|csv|md|txt" title="...">...</artifact>
    tags, compile each into a real downloadable file, and return (cleaned_response, artifacts_list).
    """
    if not response_text:
        return "", []

    pattern = re.compile(
        r'<artifact\s+[^>]*type=["\']([a-zA-Z0-9]+)["\'][^>]*title=["\']([^"\']+)["\'][^>]*>(.*?)</artifact>'
        r'|<artifact\s+[^>]*title=["\']([^"\']+)["\'][^>]*type=["\']([a-zA-Z0-9]+)["\'][^>]*>(.*?)</artifact>',
        re.DOTALL | re.IGNORECASE,
    )

    artifacts: List[Dict[str, Any]] = []

    def _replacer(match: re.Match) -> str:
        if match.group(1):
            fmt = match.group(1).lower()
            title = match.group(2).strip()
            body = match.group(3).strip()
        else:
            title = match.group(4).strip()
            fmt = match.group(5).lower()
            body = match.group(6).strip()

        try:
            rec = create_export_file(
                conversation_id=conversation_id,
                title=title,
                content=body,
                file_format=fmt,
            )
            artifacts.append(rec)
            return f"\n\n> **Generated Artifact:** `{rec['filename']}` ({fmt.upper()}) — Ready for preview and download below.\n\n"
        except Exception as e:
            print(f"Artifact compilation error: {e}")
            return body

    cleaned_text = pattern.sub(_replacer, response_text).strip()
    return cleaned_text, artifacts

